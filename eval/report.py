"""Aggregate per-run metrics into Markdown + LaTeX summaries."""

from __future__ import annotations

import json
import statistics
from pathlib import Path
from typing import Iterable


def _mean_std(values: Iterable[float]) -> tuple[float, float]:
    vs = list(values)
    if not vs:
        return 0.0, 0.0
    if len(vs) == 1:
        return float(vs[0]), 0.0
    return statistics.mean(vs), statistics.stdev(vs)


def _fmt(value: float, std: float, fmt: str = "{:.1f}") -> str:
    if std == 0.0:
        return fmt.format(value)
    return f"{fmt.format(value)} $\\pm$ {fmt.format(std)}"


def _aggregate(runs: list[dict]) -> dict:
    return {
        "n": len(runs),
        "wall_clock_seconds": _mean_std(r["wall_clock_seconds"] for r in runs),
        "total_tool_calls": _mean_std(r["total_tool_calls"] for r in runs),
        "redundant_tool_calls": _mean_std(r["redundant_tool_calls"] for r in runs),
        "tool_invocation_accuracy_pct": _mean_std(
            r["tool_invocation_accuracy_pct"] for r in runs
        ),
        "reports_covering_all_stages": sum(
            1 for r in runs if r["report_covers_all_stages"]
        ),
    }


def write_summary(all_results: dict[str, list[dict]], out_dir: Path) -> None:
    """Write summary.json, summary.md, summary.tex into out_dir."""
    out_dir.mkdir(parents=True, exist_ok=True)
    aggregates = {version: _aggregate(runs) for version, runs in all_results.items()}

    (out_dir / "summary.json").write_text(
        json.dumps(
            {"per_run": all_results, "aggregates": {v: _to_jsonable(a) for v, a in aggregates.items()}},
            indent=2,
        )
    )

    (out_dir / "summary.md").write_text(_render_markdown(aggregates))
    (out_dir / "summary.tex").write_text(_render_latex(aggregates))


def _to_jsonable(agg: dict) -> dict:
    out = {"n": agg["n"], "reports_covering_all_stages": agg["reports_covering_all_stages"]}
    for k, v in agg.items():
        if isinstance(v, tuple):
            out[k] = {"mean": v[0], "stdev": v[1]}
    return out


def _render_markdown(aggregates: dict[str, dict]) -> str:
    versions = list(aggregates.keys())
    header = "| Metric | " + " | ".join(f"{v} (n={aggregates[v]['n']})" for v in versions) + " |"
    sep = "|---|" + "|".join(["---" for _ in versions]) + "|"
    lines = ["# V1 vs V2 evaluation summary", "", header, sep]

    def row(label: str, key: str, fmt: str) -> str:
        cells = []
        for v in versions:
            mean, std = aggregates[v][key]
            cells.append(_md_fmt(mean, std, fmt))
        return f"| {label} | " + " | ".join(cells) + " |"

    lines.append(row("End-to-end time (s)", "wall_clock_seconds", "{:.1f}"))
    lines.append(row("Tool calls per run", "total_tool_calls", "{:.1f}"))
    lines.append(row("Redundant tool calls", "redundant_tool_calls", "{:.1f}"))
    lines.append(row("Tool invocation accuracy (%)", "tool_invocation_accuracy_pct", "{:.1f}"))

    cells = []
    for v in versions:
        cells.append(f"{aggregates[v]['reports_covering_all_stages']}/{aggregates[v]['n']}")
    lines.append(f"| Reports covering all stages | " + " | ".join(cells) + " |")

    lines.append("")
    return "\n".join(lines) + "\n"


def _md_fmt(mean: float, std: float, fmt: str) -> str:
    if std == 0.0:
        return fmt.format(mean)
    return f"{fmt.format(mean)} ± {fmt.format(std)}"


def _render_latex(aggregates: dict[str, dict]) -> str:
    """Drop-in tabular block matching the paper's Table 1 column order."""
    v1 = aggregates.get("v1")
    v2 = aggregates.get("v2")
    if not v1 or not v2:
        return "% summary.tex skipped: need both v1 and v2 results to render the paper table\n"

    lines = [
        "% Generated by eval/run_eval.py — paste into Camera Ready Draft.tex Section 5.3",
        "% Replaces the contents of the tabular environment in Table 1 (label tab:v1_vs_v2).",
        "\\begin{tabular}{lcc}",
        "\\toprule",
        "\\textbf{Metric} & \\textbf{V1 (single-agent)} & \\textbf{V2 (multi-agent)} \\\\",
        "\\midrule",
        f"End-to-end time (s)         & {_fmt(*v1['wall_clock_seconds'], '{:.1f}')} & {_fmt(*v2['wall_clock_seconds'], '{:.1f}')} \\\\",
        f"Tool calls per run          & {_fmt(*v1['total_tool_calls'], '{:.1f}')} & {_fmt(*v2['total_tool_calls'], '{:.1f}')} \\\\",
        f"Redundant tool calls        & {_fmt(*v1['redundant_tool_calls'], '{:.1f}')} & {_fmt(*v2['redundant_tool_calls'], '{:.1f}')} \\\\",
        f"Tool invocation accuracy    & {_fmt(*v1['tool_invocation_accuracy_pct'], '{:.0f}')}\\% & {_fmt(*v2['tool_invocation_accuracy_pct'], '{:.0f}')}\\% \\\\",
        f"Reports covering all stages & {v1['reports_covering_all_stages']}/{v1['n']} & {v2['reports_covering_all_stages']}/{v2['n']} \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "",
    ]
    return "\n".join(lines)
